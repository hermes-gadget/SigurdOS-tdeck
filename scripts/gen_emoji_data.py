def generate_lookup(emoji_list: list[str]) -> list[tuple[str, str]]:
    """Generate (short_name, utf8_emoji) pairs, using defaults for unnamed ones."""
    result = []
    unnamed = 0
    for emoji in emoji_list:
        name = SHORT_NAMES.get(emoji)
        if name:
            result.append((name, emoji))
        else:
            unnamed += 1

    print(f"Named: {len(result)}, Unnamed: {unnamed}", file=sys.stderr)

    # Sort by name for binary search
    result.sort(key=lambda x: x[0])
    return result


def generate_header(pairs: list[tuple[str, str]], output_path: str):
    """Generate emoji_data.h"""
    lines = [
        '#ifndef EMJI_DATA_H',
        '#define EMJI_DATA_H',
        '',
        '#include <cstdint>',
        '',
        '// Discord-style emoji short name + UTF-8 lookup',
        '// Sorted alphabetically by short_name for binary search',
        '',
        'struct EmojiEntry {',
        '    const char* short_name;  // e.g. "smile"',
        '    const char* utf8;        // UTF-8 emoji string',
        '};',
        '',
        f'static constexpr int EMOJI_DATA_COUNT = {len(pairs)};',
        '',
        'extern const EmojiEntry emoji_data[];',
        '',
        f'// Binary search: find emoji by short name prefix. Returns count of matches.', 
        '// Results written to out[] up to max_results. Returns number of matches found.',
        f'int emoji_search(const char* prefix, EmojiEntry* out, int max_results);',
        '',
        '#endif  // EMJI_DATA_H',
    ]

    with open(output_path, 'w') as f:
        for line in lines:
            f.write(line + '\n')
    print(f"Wrote {output_path}", file=sys.stderr)


def generate_source(pairs: list[tuple[str, str]], output_path: str):
    """Generate emoji_data.cpp with sorted data + binary search"""
    lines = [
        '#include "emoji_data.h"',
        '#include <cstring>',
        '',
        'const EmojiEntry emoji_data[] = {',
    ]

    for name, emoji in pairs:
        # Escape the UTF-8 string as hex escapes
        escaped = ''.join(f'\\x{b:02x}' for b in emoji.encode('utf-8'))
        lines.append(f'    {{"{name}", "{escaped}"}},')

    lines.extend([
        '};',
        '',
        'int emoji_search(const char* prefix, EmojiEntry* out, int max_results)',
        '{',
        '    if (!prefix || !prefix[0]) return 0;',
        '    int len = (int)strlen(prefix);',
        '    int count = 0;',
        '',
        '    // Binary search for the first match (prefix start)',
        '    int lo = 0;',
        f'    int hi = EMOJI_DATA_COUNT;',
        '    while (lo < hi) {',
        '        int mid = (lo + hi) / 2;',
        '        int cmp = strncmp(emoji_data[mid].short_name, prefix, len);',
        '        if (cmp < 0) lo = mid + 1;',
        '        else hi = mid;',
        '    }',
        '',
        '    // Collect all matches starting from lo',
        '    for (int i = lo; i < EMOJI_DATA_COUNT && count < max_results; i++) {',
        '        if (strncmp(emoji_data[i].short_name, prefix, len) != 0) break;',
        '        out[count++] = emoji_data[i];',
        '    }',
        '',
        '    return count;',
        '}',
    ])

    with open(output_path, 'w') as f:
        for line in lines:
            f.write(line + '\n')
    print(f"Wrote {output_path}", file=sys.stderr)


def main():
    src_dir = Path(__file__).parent.parent / 'src'
    emoji_setup = src_dir / 'fonts' / 'emoji_font_setup.cpp'
    out_h = src_dir / 'fonts' / 'emoji_data.h'
    out_cpp = src_dir / 'fonts' / 'emoji_data.cpp'

    emoji_list = parse_emoji_list(str(emoji_setup))
    pairs = generate_lookup(emoji_list)
    print(f"Generated {len(pairs)} named emoji entries", file=sys.stderr)

    generate_header(pairs, str(out_h))
    generate_source(pairs, str(out_cpp))

    print("Done!", file=sys.stderr)


if __name__ == '__main__':
    main()
