"""Generate emoji_data.h / emoji_data.cpp from the existing emoji font setup.

Reads emoji_list[] from emoji_font_setup.cpp, maps codepoints to Discord-style
short names using Unicode CLDR annotations, and outputs sorted lookup tables.
"""

import re
import sys
import json
from pathlib import Path

# ── Parse emoji_font_setup.cpp to extract UTF-8 emoji strings ──
def parse_emoji_list(source_path: str) -> list[str]:
    """Extract UTF-8 emoji strings from emoji_font_setup.cpp's emoji_list[]."""
    with open(source_path, 'r') as f:
        content = f.read()

    # Find emoji_list array
    m = re.search(r'static const char\* emoji_list\[\] = \{([^}]+)\}', content, re.DOTALL)
    if not m:
        raise ValueError("Could not find emoji_list[] in source")

    array_text = m.group(1)
    # Match string literals like "\xF0\x9F\x98\x80"
    pattern = re.findall(r'"((?:\\x[0-9A-Fa-f]{2})+)"', array_text)
    result = []
    for hex_str in pattern:
        # Convert \xNN sequences to bytes, then decode as UTF-8
        bytes_arr = bytes(int(h, 16) for h in re.findall(r'\\x([0-9A-Fa-f]{2})', hex_str))
        result.append(bytes_arr.decode('utf-8'))

    print(f"Parsed {len(result)} emoji from emoji_font_setup.cpp", file=sys.stderr)
    return result


